/**
 * Brand glyphs for the messaging channels.
 *
 * The paths come from Simple Icons (MIT licensed), 24x24 grid. Each vector is
 * filled with white so it can be dropped on a tile painted in the brand colour —
 * a tint would flatten the shape into the tile colour and hide it.
 *
 * Why they are vendored: `material-icons-extended` is not published for
 * Compose Multiplatform after 1.7.3, and brand marks are not in Material
 * Symbols at all. Three small vectors are cheaper than a font or an asset
 * pipeline.
 */
internal object BrandMarks {
    val Telegram: ImageVector = brandVector("brand_telegram", TELEGRAM_PATH)

    val Slack: ImageVector = brandVector("brand_slack", SLACK_PATH)

    val WhatsApp: ImageVector = brandVector("brand_whatsapp", WHATSAPP_PATH)

    private fun brandVector(
        name: String,
        pathData: String,
    ): ImageVector =
        ImageVector
            .Builder(
                name = name,
                defaultWidth = 24.dp,
                defaultHeight = 24.dp,
                viewportWidth = 24f,
                viewportHeight = 24f,
            ).addPath(
                pathData = addPathNodes(pathData),
                fill = SolidColor(Color.White),
            ).build()
}

/** A brand glyph together with the colour of the tile it belongs on. */
internal data class BrandMark(
    val vector: ImageVector,
    val color: Color,
)

/**
 * The brand mark for a platform id, or null when the platform has no known
 * brand (the caller then draws a neutral tile).
 */
internal fun brandMarkFor(platformId: String): BrandMark? {
    val id = platformId.lowercase()
    return when (id) {
        "telegram" -> BrandMark(BrandMarks.Telegram, Color(0xFF2AABEE))
        "slack" -> BrandMark(BrandMarks.Slack, Color(0xFF4A154B))
        "whatsapp" -> BrandMark(BrandMarks.WhatsApp, Color(0xFF25D366))
        else -> null
    }
}

